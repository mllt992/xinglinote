import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { chromium } from "playwright-core";
const base = process.env.KB_UI_BASE_URL || "http://127.0.0.1:12148";
const browser = await chromium.launch({ executablePath: process.env.KB_CHROMIUM_EXECUTABLE || "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true });
await mkdir("artifacts", { recursive: true });
try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  let user = "mock-alice", failSelection = false, hold = false, release;
  const asks = [];
  const waitForAsk = async (page, count) => { for (let i = 0; i < 30 && asks.length < count; i++) await page.waitForTimeout(50); assert.equal(asks.length, count); };
  await context.routeWebSocket(/.*/, ws => ws.close());
  await context.route("**/api/**", async route => {
    const path = new URL(route.request().url()).pathname;
    let data = { notifications: [], unread: 0, notes: [], projects: [], folders: [], notebooks: [], workspaces: [] };
    if (path === "/api/v1/me") data = { id: user, displayName: user, appearance: "light", themeId: "mono-modern", personalWorkspaceId: "ws-a", instanceRole: "user" };
    else if (path === "/api/v1/workspaces") data = { workspaces: [{ id: "ws-a", name: "空间甲", role: "owner" }, { id: "ws-b", name: "空间乙", role: "owner" }] };
    else if (path === "/api/v1/meta") data = { squareEnabled: false, navEnabled: false };
    else if (path.endsWith("/ai/chat-options")) data = { userId: user, channels: [{ id: "personal", name: "我的渠道", source: "个人", models: ["personal-model"] }, { id: "platform", name: "平台渠道", source: "平台", models: ["platform-model"] }], effective: { providerId: "personal", model: "personal-model", source: "个人" }, explicitWorkspace: false };
    else if (path === "/api/v1/ai/ask/stream") {
      asks.push(route.request().postDataJSON());
      if (failSelection) { await route.fulfill({ status: 403, contentType: "application/json", body: JSON.stringify({ ok: false, error: { code: "FORBIDDEN", message: "所选 AI 渠道不可用或无权使用，请重新选择" } }) }); return; }
      if (hold) await new Promise(resolve => { release = resolve; });
      const answer = hold ? "旧账号旧空间答案不可出现" : "模拟回答";
      await route.fulfill({ contentType: "application/x-ndjson", body: JSON.stringify({ type: "delta", delta: answer }) + "\n" + JSON.stringify({ type: "done", data: { answer, citations: [], grounded: false } }) + "\n" }).catch(() => {});
      return;
    }
    await route.fulfill({ contentType: "application/json", body: JSON.stringify({ ok: true, data }) }).catch(() => {});
  });
  const page = await context.newPage();
  await page.goto(`${base}/w/ws-a`);
  await page.getByRole("button", { name: "问知识库", exact: true }).click();
  const model = page.getByLabel("对话模型", { exact: true });
  await model.waitFor();
  await page.getByText("当前：personal-model · 个人", { exact: false }).waitFor();
  await model.selectOption(JSON.stringify({ providerId: "platform", model: "platform-model" }));
  await page.getByText("当前：platform-model · 平台", { exact: false }).waitFor();
  const question = page.locator("aside textarea");
  await question.fill("测试模型选择");
  await page.getByRole("button", { name: "提问", exact: true }).click();
  await page.getByText("模拟回答", { exact: true }).waitFor();
  assert.deepEqual(asks[0].selection, { providerId: "platform", model: "platform-model" });
  failSelection = true;
  await question.fill("测试明确失效");
  await page.getByRole("button", { name: "提问", exact: true }).click();
  await page.getByText("所选 AI 渠道不可用或无权使用，请重新选择", { exact: true }).waitFor();
  assert.equal(asks.length, 2);
  assert.deepEqual(asks[1].selection, asks[0].selection);
  assert.equal(await model.inputValue(), JSON.stringify(asks[0].selection));
  await page.screenshot({ path: "artifacts/ai-model-source-error.png", fullPage: true });
  failSelection = false; hold = true;
  await question.fill("测试旧空间响应");
  await page.getByRole("button", { name: "提问", exact: true }).click();
  await waitForAsk(page, 3);
  assert.equal(asks[2].workspaceId, "ws-a");
  await page.waitForFunction(() => document.querySelector("aside textarea")?.disabled);
  await page.getByRole("button", { name: "空间甲", exact: true }).click();
  await page.getByRole("menuitem", { name: "空间乙", exact: false }).click();
  await page.waitForURL(url => url.pathname.startsWith("/w/ws-b"));
  release?.();
  await page.waitForTimeout(200);
  assert.equal(await page.getByText("旧账号旧空间答案不可出现", { exact: true }).count(), 0);
  if (!await model.count()) await page.getByRole("button", { name: "问知识库", exact: true }).click();
  await model.waitFor();
  await question.fill("测试旧账号响应");
  await page.getByRole("button", { name: "提问", exact: true }).click();
  await waitForAsk(page, 4);
  assert.equal(asks[3].workspaceId, "ws-b");
  await page.waitForFunction(() => document.querySelector("aside textarea")?.disabled);
  user = "mock-bob";
  await page.evaluate(() => window.dispatchEvent(new Event("kb:me-updated")));
  await page.waitForTimeout(200);
  release?.();
  await page.waitForTimeout(200);
  assert.equal(await page.getByText("旧账号旧空间答案不可出现", { exact: true }).count(), 0);
  assert.equal(await page.getByText("测试旧账号响应", { exact: true }).count(), 0);
  await page.screenshot({ path: "artifacts/ai-account-isolation.png", fullPage: true });
  console.log("PASS: source labels, selected request, explicit failure without fallback, workspace/account stale stream isolation; all API routes mocked");
  await context.close();
} finally { await browser.close(); }
